import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SUPPORTED_PACKS, buildItemSource, validateDefinition } from "./lib/content-contract.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const output = path.join(root, "scripts", "bundled-content.js");
const byPack = {};

for (const pack of SUPPORTED_PACKS) {
  const directory = path.join(root, "content", pack);
  const files = (await fs.readdir(directory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) => entry.name)
    .sort();
  byPack[pack] = [];
  for (const filename of files) {
    const sourcePath = path.join(directory, filename);
    const definition = JSON.parse(await fs.readFile(sourcePath, "utf8"));
    const issues = validateDefinition(definition, { pack });
    if (issues.length) throw new Error(`${filename} is not publishable:\n${issues.map((issue) => `- ${issue}`).join("\n")}`);
    byPack[pack].push(buildItemSource(definition));
  }
}

const source = `// Generated by tools/generate-runtime-seed.mjs. Do not edit by hand.\nexport const BUNDLED_ITEM_SOURCES_BY_PACK = Object.freeze(${JSON.stringify(byPack, null, 2)});\n`;
await fs.writeFile(output, source, "utf8");
console.log(`Generated ${path.relative(root, output)} with ${Object.values(byPack).flat().length} bundled Item source(s).`);
